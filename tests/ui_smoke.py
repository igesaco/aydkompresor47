import sys,tempfile, json, shutil
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent.parent))
from ayd.db import Database
from ayd.demo import populate
from ayd.server import launch_server
from playwright.sync_api import sync_playwright, expect

with tempfile.TemporaryDirectory() as folder:
    database=Database(Path(folder)/'test.sqlite3')
    populate(database)
    server,url=launch_server(database)
    errors=[]
    with sync_playwright() as p:
        browser=p.chromium.launch(executable_path=shutil.which('chromium') or shutil.which('google-chrome'),headless=True)
        page=browser.new_page(viewport={'width':1440,'height':1100},device_scale_factor=1)
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(url)
        page.get_by_role('heading',name='Atölyenize genel bir bakış.').wait_for()
        page.screenshot(path=str(Path(tempfile.gettempdir())/'ayd-dashboard.png'),full_page=True)
        for view in ['customers','compressors','services','stock','ledger','invoices','calendar','alerts','settings']:
            page.goto(url.split('/?')[0]+'/#'+view)
            page.locator('h1').wait_for()
            assert page.locator('h1').inner_text(),view
        page.goto(url.split('/?')[0]+'/#customers')
        page.get_by_role('button',name='Müşteri ekle',exact=True).click()
        page.get_by_label('Firma / Müşteri adı *').fill('Tarayıcı Test Müşterisi')
        page.get_by_label('Telefon',exact=True).fill('0555 111 22 33')
        page.get_by_role('button',name='Kaydet',exact=True).click()
        page.get_by_role('button',name='Tarayıcı Test Müşterisi',exact=True).wait_for()
        page.get_by_placeholder('İsim, telefon veya vergi no ile ara…').fill('Tarayıcı Test')
        expect(page.locator('tbody tr')).to_have_count(1)
        page.get_by_role('button',name='Müşteri kartı →').click()
        page.get_by_role('heading',name='Tarayıcı Test Müşterisi').wait_for()
        page.goto(url.split('/?')[0]+'/#invoices')
        page.get_by_role('button',name='Proforma oluştur',exact=True).click()
        page.get_by_label('Müşteri *',exact=True).select_option(label='Mavişehir Otomotiv')
        page.locator('[name="item_stock"]').select_option('1')
        page.locator('[name="item_quantity"]').fill('2')
        assert '1.080' in page.locator('#invoice-total').inner_text()
        page.get_by_role('button',name='Kaydet',exact=True).click()
        page.locator('#modal').wait_for(state='hidden')
        expect(page.locator('tbody tr')).to_have_count(2)
        page.get_by_role('button',name='Görüntüle',exact=True).first.click()
        assert page.locator('.print-sheet').is_visible()
        page.screenshot(path=str(Path(tempfile.gettempdir())/'ayd-proforma.png'),full_page=True)
        page.get_by_role('button',name='Kapat',exact=True).click()
        page.goto(url.split('/?')[0]+'/#services')
        page.get_by_role('button',name='Servis kaydı',exact=True).click()
        page.get_by_label('Kompresör *',exact=True).select_option('3')
        page.locator('.recommendation').wait_for()
        assert 'Filtre' in page.locator('.recommendation').inner_text() or 'filtre' in page.locator('.recommendation').inner_text()
        page.get_by_label('İşlem başlığı *').fill('UI bakım testi')
        page.get_by_label('Yapılan / Planlanan işlemler *').fill('Filtre kontrol edildi.')
        page.get_by_label('Durum *',exact=True).select_option('Tamamlandı')
        page.get_by_label('Toplam servis bedeli (TL)').fill('500')
        page.get_by_role('button',name='+ Parça ekle',exact=True).click()
        page.locator('[name="part_stock"]').select_option('1')
        page.get_by_role('button',name='Kaydet',exact=True).click()
        page.locator('#modal').wait_for(state='hidden')
        page.get_by_text('UI bakım testi',exact=True).wait_for()
        page.goto(url.split('/?')[0]+'/#stock')
        assert page.locator('tbody tr').filter(has_text='Hava filtresi').first.locator('td').nth(1).inner_text().startswith('2 adet')
        page.goto(url.split('/?')[0]+'/#calendar')
        page.get_by_role('button',name='Randevu ekle',exact=True).click()
        page.get_by_label('Randevu / İş başlığı *').fill('UI randevu testi')
        page.get_by_role('button',name='Kaydet',exact=True).click()
        page.locator('#modal').wait_for(state='hidden')
        page.get_by_role('button',name='09:00 UI randevu testi',exact=True).wait_for()
        page.goto(url.split('/?')[0]+'/#settings')
        with page.expect_download() as download_info:
            page.get_by_role('link',name='Şimdi yedek indir').click()
        download=download_info.value
        download.save_as(str(Path(folder)/'ui-backup.sqlite3'))
        assert Path(str(Path(folder)/'ui-backup.sqlite3')).read_bytes().startswith(b'SQLite format 3')
        page.set_viewport_size({'width':1100,'height':800})
        page.goto(url.split('/?')[0]+'/#dashboard')
        page.locator('.stats').wait_for()
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
        page.set_viewport_size({'width':390,'height':844})
        page.screenshot(path=str(Path(tempfile.gettempdir())/'ayd-mobile.png'),full_page=True)
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
        assert not errors,errors
        print(json.dumps({'ui':'passed','pages':10,'customer_create_search_history':True,'proforma_create_print':True,'service_stock_recommendations':True,'appointment':True,'backup_download':True,'responsive':[1440,1100,390],'javascript_errors':errors}))
        browser.close()
    server.shutdown()
